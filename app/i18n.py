def get_lang(request: Request) -> str:
    """Determine language from cookie, then Accept-Language header. Default: de."""
    lang = request.cookies.get("lang")
    if lang in T:
        return lang
    accept = request.headers.get("accept-language", "")
    if "en" in accept and "de" not in accept:
        return "en"
    return "de"


